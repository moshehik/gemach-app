export const POLICY_UPDATED = '2026-10-04';

export const PRIVACY_TITLE = 'מדיניות פרטיות';
export const PRIVACY_SUB = 'איך נשמר המידע של הלקוחות';
export const PRIVACY_DEFAULT_NAME = 'גמ״ח שמלות';
