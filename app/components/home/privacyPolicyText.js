// מפרק טקסט לקטעים: { text, ph } — ph = שדה מילוי (בין [[ ]])
export function splitPlaceholders(text) {
  const out = [];
  const re = /\[\[([^\]]+)\]\]/g;
  let last = 0;
  let m;
  const s = String(text || '');
  while ((m = re.exec(s)) !== null) {
    if (m.index > last) out.push({ text: s.slice(last, m.index), ph: false });
    out.push({ text: '[' + m[1] + ']', ph: true });
    last = m.index + m[0].length;
  }
  if (last < s.length) out.push({ text: s.slice(last), ph: false });
  return out;
}

