const clean = (v) => (v === null || v === undefined ? '' : String(v).replace(/\s+/g, ' ').trim());

/** תאריך אישור הנוסח כתאריך עברי (בלי תאריך לועזי), לפי היום הקלנדרי בישראל. */
export function policyUpdatedHebrew() {
  return hebrewDateOfInstant(`${POLICY_UPDATED}T12:00:00+03:00`);
}

/** שורת הפנייה לפרטיות: בנויה מהטלפון בהגדרות (gmach_phone) של הגמ"ח הנוכחי. */
export function privacyContactLine(phone) {
  const p = clean(phone);
  return p
    ? `לפניות: בטלפון הגמ"ח, ${p}.`
    : 'לפניות: ניתן לפנות אלינו ישירות בגמ"ח.';
}

