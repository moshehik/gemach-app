/** מחליף את הסימנים. contactLines: מערך שורות (טקסט פשוט). שורת קשר ריקה נופלת לניסוח כללי. */
export function renderPrivacyText(template, { name, contactLines } = {}) {
  const gmachName = String(name || '').trim() || 'הגמ"ח';
  const lines = (contactLines || []).map((l) => String(l || '').trim()).filter(Boolean);
  const contact = lines.length
    ? lines.map((l) => `- ${l}`).join('\n')
    : 'ניתן לפנות אלינו בדרכי ההתקשרות של הגמ"ח המפורסמות בחנות.';
  return String(template || '')
    .replace(/\{\{\s*שם\s*\}\}/g, gmachName)
    .replace(/\{\{\s*פרטי_קשר\s*\}\}/g, contact);
}

/** הטקסט בפועל: ההגדרה privacy_policy_text אם מולאה (לא ריקה), אחרת ברירת המחדל. */
export function effectivePrivacyTemplate(settingValue) {
  const v = typeof settingValue === 'string' ? settingValue.replace(/\r\n/g, '\n').trim() : '';
  return v ? v : DEFAULT_PRIVACY_POLICY_TEXT;
}

/** מפרק טקסט לבלוקים להצגה: [{type:'h'|'p'|'ul', text|items}] - רק טקסט, לעולם לא HTML. */
export function parsePolicyBlocks(text) {
  const blocks = [];
  let list = null;
  let para = [];
  const flushPara = () => { if (para.length) { blocks.push({ type: 'p', text: para.join(' ') }); para = []; } };
  const flushList = () => { if (list) { blocks.push({ type: 'ul', items: list }); list = null; } };
  for (const raw of String(text || '').replace(/\r\n/g, '\n').split('\n')) {
    const line = raw.trim();
    if (!line) { flushPara(); flushList(); continue; }
    if (line.startsWith('## ')) { flushPara(); flushList(); blocks.push({ type: 'h', text: line.slice(3).trim() }); continue; }
    if (line.startsWith('- ')) { flushPara(); (list = list || []).push(line.slice(2).trim()); continue; }
    flushList();
    para.push(line);
  }
  flushPara(); flushList();
  return blocks;
}
