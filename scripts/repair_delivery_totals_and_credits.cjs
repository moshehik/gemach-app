// תיקון חד-פעמי (נווה יעקב בלבד) להזמנות משלוח: סכום שמור שחסר בו חיוב המשלוח + זיכוי אוטומטי פתוח שגוי.
// רקע, היקף וסדר: docs/delivery-total-and-credit-fix-2026-10-12.md. הקוד עצמו תוקן ב-PR 274 (applyDeliveryCharge מעדכן totalAmount ומסנכרן זיכוי).
//
// מה נוגעים (רק): הזמנות משלוח עם חיוב "משלוח" חי, totalAmount>0 שחסר בו בדיוק סכום המשלוח, ועם *זיכוי אוטומטי אחד* פתוח (לא בוצע, לא נמחק)
//   שסכומו שונה מהזיכוי האמיתי = max(0, שולם - חיובים חיים - זיכויים פתוחים אחרים).
//   -> Order.totalAmount = סכום החיובים החיים; הזיכוי: אפס = מחיקה רכה (AUTO_CREDIT_REFUND_CLEARED), אחרת עדכון סכום (AUTO_CREDIT_REFUND_UPDATED).
// מה לא נוגעים: זיכויים שבוצעו/ידניים, הזמנות בלי זיכוי פתוח, הזמנות בלי חיוב משלוח, זיכוי חסר (יצירה), לקוחות ניסוי (--exclude-customer=<id>),
//   זיכוי אוטומטי שכבר הוזנו בו פרטי בנק (נרשם "לבדיקה ידנית" ולא נמחק), ואם מצב ההזמנה השתנה מאז התכנון - מדולג.
// בטיחות: dry-run כברירת מחדל. כתיבה רק עם --write --i-understand --expect-host=<תחילית host>; org2 בלבד; host שונה מ-org1; גיבוי JSON לפני כתיבה;
//   כל הזמנה בטרנזקציה נפרדת עם נעילה (FOR UPDATE) ושורות AuditLog מקבילות (הסקריפט עוקף את תוסף היומן). Order.updatedAt לא משתנה (כדי לא ליצור "הזמנה עודכנה בשרת").
//
//   node scripts/repair_delivery_totals_and_credits.cjs --org=2 --orders=<csv ids | @file> --exclude-customer=<id>[,<id>] [--backup-dir=<dir>]     (dry-run)
//   ... --write --i-understand --expect-host=<תחילית host>                                                                                       (כתיבה)
// מריצים מתוך שורש הריפו עם .env (PROD_DATABASE_URL / PROD_DATABASE_URL_ORG2) ו-pg ב-node_modules; לא מדפיס כתובות חיבור.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { Client } = require('pg');

const arg = (n) => { const a = process.argv.find((x) => x.startsWith(`--${n}=`)); return a ? a.slice(n.length + 3) : null; };
const flag = (n) => process.argv.includes(`--${n}`);
const r2 = (n) => Math.round((Number(n) + Number.EPSILON) * 100) / 100;
const hostOf = (u) => (String(u).match(/@([^/?]+)/) || [])[1] || '';
const NOTE = 'repair_delivery_totals_and_credits 2026-10-12 (PR 274)';

const env = {};
for (const l of fs.readFileSync(path.join(process.cwd(), '.env'), 'utf8').split(/\r?\n/)) {
  const m = l.match(/^([A-Z_0-9]+)=(.*)$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}

async function evaluate(q, orderId, lock) {
  const o = (await q(`select o."orderId", o."totalAmount", o."isDelivery", o."customerId", coalesce(o."isDeleted",false) del from "Order" o where o."orderId"=$1 ${lock ? 'for update of o' : ''}`, [orderId])).rows[0];
  if (!o) return { skip: 'ההזמנה לא נמצאה' };
  const obl = (await q(`select coalesce(sum(amount),0) s from "PaymentObligation" where "orderId"=$1 and not "isDeleted"`, [orderId])).rows[0].s;
  const dlv = (await q(`select coalesce(sum(amount),0) s, count(*) n from "PaymentObligation" where "orderId"=$1 and not "isDeleted" and description like '%משלוח%'`, [orderId])).rows[0];
  const paid = (await q(`select coalesce(sum(amount),0) s from "Payment" where "orderId"=$1 and not "isDeleted"`, [orderId])).rows[0].s;
  const open = (await q(`select id, amount, "isAutoGenerated", "bankName", "bankBranch" from "Refund" where "orderId"=$1 and not "isDeleted" and not "isExecuted"`, [orderId])).rows;
  return { o, obl: r2(obl), dlv: r2(dlv.s), dlvRows: Number(dlv.n), paid: r2(paid), open };
}

function decide(e, excluded) {
  if (e.skip) return e;
  const { o } = e;
  if (excluded.has(o.customerId)) return { skip: 'לקוח ניסוי - לא נוגעים' };
  if (!o.isDelivery || o.del) return { skip: 'לא הזמנת משלוח פעילה' };
  if (e.dlv <= 0) return { skip: 'אין חיוב משלוח חי בסכום חיובי' };
  const total = o.totalAmount == null ? null : r2(o.totalAmount);
  if (!(total > 0) || Math.abs((e.obl - total) - e.dlv) > 0.01) return { skip: 'totalAmount לא חסר בדיוק את סכום המשלוח' };
  const autos = e.open.filter((r) => r.isAutoGenerated);
  if (autos.length !== 1) return { skip: `מספר זיכויים אוטומטיים פתוחים = ${autos.length} (נדרש 1)` };
  const auto = autos[0];
  const others = r2(e.open.filter((r) => !r.isAutoGenerated).reduce((s, r) => s + r.amount, 0));
  const target = r2(Math.max(0, e.paid - e.obl - others));
  if (Math.abs(r2(auto.amount) - target) <= 0.01) return { skip: 'הזיכוי כבר נכון' };
  if (target === 0 && ((auto.bankName || '').trim() || (auto.bankBranch || '').trim())) return { skip: 'לבדיקה ידנית: הוזנו פרטי בנק בזיכוי שהיה נמחק' };
  return { ok: true, total, newTotal: e.obl, refundId: auto.id, refundNow: r2(auto.amount), refundTarget: target, action: target === 0 ? 'מחיקה רכה' : 'עדכון סכום' };
}

(async () => {
  const org = Number(arg('org'));
  if (org !== 2) throw new Error('הסקריפט מיועד ל-org=2 (נווה יעקב) בלבד');
  const write = flag('write');
  const url = env.PROD_DATABASE_URL_ORG2;
  const host = hostOf(url);
  const otherHost = hostOf(env.PROD_DATABASE_URL);
  if (!host || host === otherHost) throw new Error(`SAFETY ABORT: host "${host}" ריק או זהה ל-org1`);
  if (write) {
    if (!flag('i-understand')) throw new Error('כתיבה דורשת --i-understand');
    const eh = arg('expect-host');
    if (!eh || !host.startsWith(eh)) throw new Error(`כתיבה דורשת --expect-host שמתחיל ב-"${host.slice(0, 12)}"`);
  }
  let ids = arg('orders');
  if (!ids) throw new Error('חסר --orders=<csv|@file>');
  ids = (ids.startsWith('@') ? fs.readFileSync(ids.slice(1), 'utf8') : ids).split(/[\s,]+/).filter(Boolean).map(Number);
  const excluded = new Set((arg('exclude-customer') || '').split(',').filter(Boolean));
  const backupDir = arg('backup-dir') || path.join(process.cwd(), 'scratch', 'delivery-repair-backup-2026-10-12');
  console.log(`org2 host: ${host} | mode: ${write ? 'WRITE' : 'dry-run'} | orders: ${ids.length} | excluded customers: ${excluded.size}`);

  const c = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
  await c.connect();
  if (!write) await c.query('SET default_transaction_read_only = on');
  const q = (sql, p) => c.query(sql, p);

  const plans = [];
  const skipped = [];
  for (const id of ids) {
    const d = decide(await evaluate(q, id, false), excluded);
    (d.ok ? plans : skipped).push({ orderId: id, ...d });
  }
  const sumDelta = plans.reduce((s, p) => s + (p.refundNow - p.refundTarget), 0);
  console.log(`\nלתיקון: ${plans.length} (מחיקה רכה ${plans.filter((p) => p.action === 'מחיקה רכה').length}, עדכון סכום ${plans.filter((p) => p.action === 'עדכון סכום').length}) | זיכוי עודף שיוסר: ${r2(sumDelta)} ₪`);
  console.log(`מדולגים: ${skipped.length}`);
  const bySkip = {};
  skipped.forEach((s) => { bySkip[s.skip] = (bySkip[s.skip] || []).concat(s.orderId); });
  Object.entries(bySkip).forEach(([k, v]) => console.log(`  - ${k}: ${v.length} (${v.slice(0, 12).join(',')}${v.length > 12 ? ',...' : ''})`));

  if (!write) {
    console.log('\nDRY RUN - לא נכתב דבר.');
    await c.end();
    return;
  }

  fs.mkdirSync(backupDir, { recursive: true });
  const backup = { takenAt: new Date().toISOString(), orders: [], refunds: [] };
  for (const p of plans) {
    backup.orders.push((await q(`select * from "Order" where "orderId"=$1`, [p.orderId])).rows[0]);
    backup.refunds.push(...(await q(`select * from "Refund" where "orderId"=$1`, [p.orderId])).rows);
  }
  const bf = path.join(backupDir, `backup-${Date.now()}.json`);
  fs.writeFileSync(bf, JSON.stringify(backup, null, 1));
  console.log(`גיבוי נכתב: ${bf}`);

  const audit = (entityType, entityId, action, changes) => c.query(
    `insert into "AuditLog" (id, "entityType", "entityId", action, "changesJson", "employeeId", "updatedAt") values ($1,$2,$3,$4,$5,null,now())`,
    [crypto.randomUUID(), entityType, String(entityId), action, JSON.stringify({ ...changes, _note: NOTE })]);
  let done = 0;
  const changed = [];
  for (const p of plans) {
    try {
      await c.query('BEGIN');
      const again = decide(await evaluate(q, p.orderId, true), excluded);
      if (!again.ok || again.refundId !== p.refundId || again.refundTarget !== p.refundTarget || again.newTotal !== p.newTotal) {
        await c.query('ROLLBACK');
        changed.push({ orderId: p.orderId, why: again.skip || 'המצב השתנה מאז התכנון' });
        continue;
      }
      await q(`update "Order" set "totalAmount"=$2 where "orderId"=$1`, [p.orderId, p.newTotal]);
      await audit('Order', p.orderId, 'UPDATE', { totalAmount: { from: p.total, to: p.newTotal } });
      if (p.action === 'מחיקה רכה') {
        await q(`update "Refund" set "isDeleted"=true, "updatedAt"=now() where id=$1`, [p.refundId]);
        await audit('Refund', p.refundId, 'AUTO_CREDIT_REFUND_CLEARED', { isDeleted: { from: false, to: true }, amount: p.refundNow });
      } else {
        await q(`update "Refund" set amount=$2, "updatedAt"=now() where id=$1`, [p.refundId, p.refundTarget]);
        await audit('Refund', p.refundId, 'AUTO_CREDIT_REFUND_UPDATED', { amount: p.refundTarget, previousAmount: p.refundNow });
      }
      await c.query('COMMIT');
      done++;
    } catch (e) {
      await c.query('ROLLBACK').catch(() => {});
      changed.push({ orderId: p.orderId, why: `שגיאה: ${e.message}` });
    }
  }
  console.log(`\nנכתב: ${done}/${plans.length}. דולגו בגלל שינוי/שגיאה: ${changed.length}`);
  changed.forEach((x) => console.log('  ', JSON.stringify(x)));
  await c.end();
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
