// תוכנית תיקון (DRY-RUN בלבד - הסקריפט הזה לא כותב כלום) להזמנות משלוח בנווה יעקב:
//   1. totalAmount שמור שחסר בו בדיוק חיוב המשלוח  -> יעד: סכום החיובים החיים
//   2. זיכוי אוטומטי פתוח שסכומו שונה מהזיכוי האמיתי (שולם - חיובים) -> יעד: הסכום האמיתי (0 = מחיקה רכה)
//   3. הזמנות משלוח בלי חיוב "משלוח" חי -> רק רשימה לבדיקה ידנית (לא נוגעים)
// מפיק קובץ CSV + סיכום. כתיבה בפועל (אחרי אישור הבעלים) תיעשה דרך Prisma עם auditAs ו-syncPendingCreditRefund - ר' docs/delivery-total-and-credit-fix-2026-10-12.md סעיף 6.
//   node scripts/repair_delivery_totals_and_credits_plan.cjs <out-dir>     (מתוך שורש הריפו; קורא PROD_DATABASE_URL_ORG2 מ-.env, לא מדפיס אותו)
const fs = require('fs');
const path = require('path');
const { Client } = require('pg');
const outDir = process.argv[2];
if (!outDir) { console.error('usage: node ... <out-dir>'); process.exit(1); }
const env = {};
for (const l of fs.readFileSync(path.join(process.cwd(), '.env'), 'utf8').split(/\r?\n/)) {
  const m = l.match(/^([A-Z_0-9]+)=(.*)$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}
const r2 = (n) => Math.round((Number(n) + Number.EPSILON) * 100) / 100;
(async () => {
  const c = new Client({ connectionString: env.PROD_DATABASE_URL_ORG2, ssl: { rejectUnauthorized: false } });
  await c.connect();
  await c.query('SET default_transaction_read_only = on');
  const rows = (await c.query(`
    select o."orderId", o."eventDate", o."totalAmount", o."deliveryCity", o."deliveryDirection",
      coalesce((select sum(amount) from "PaymentObligation" p where p."orderId"=o."orderId" and not p."isDeleted"),0) obl,
      coalesce((select sum(amount) from "PaymentObligation" p where p."orderId"=o."orderId" and not p."isDeleted" and p.description like '%משלוח%'),0) dlv,
      (select count(*) from "PaymentObligation" p where p."orderId"=o."orderId" and not p."isDeleted" and p.description like '%משלוח%') dlv_rows,
      coalesce((select sum(amount) from "Payment" y where y."orderId"=o."orderId" and not y."isDeleted"),0) paid,
      (select string_agg(r.id || ':' || r.amount, ';') from "Refund" r where r."orderId"=o."orderId" and not r."isDeleted" and not r."isExecuted" and r."isAutoGenerated") autoref,
      (select coalesce(sum(r.amount),0) from "Refund" r where r."orderId"=o."orderId" and not r."isDeleted" and not r."isExecuted" and r."isAutoGenerated") autoref_sum,
      (select coalesce(sum(r.amount),0) from "Refund" r where r."orderId"=o."orderId" and not r."isDeleted" and not r."isExecuted" and not r."isAutoGenerated") other_open_refund
    from "Order" o where o."isDelivery"=true and coalesce(o."isDeleted",false)=false order by o."orderId"`)).rows;
  await c.end();

  const plan = []; const noDelivery = [];
  for (const o of rows) {
    const obl = r2(o.obl), dlv = r2(o.dlv), paid = r2(o.paid), total = o.totalAmount == null ? null : r2(o.totalAmount);
    if (Number(o.dlv_rows) === 0) { noDelivery.push({ orderId: o.orderId, eventDate: o.eventDate, city: o.deliveryCity, dir: o.deliveryDirection, total, obl, paid }); continue; }
    // שלב 1: חסר בדיוק המשלוח בסכום השמור
    if (dlv === 0) continue; // חיוב משלוח קיים בסכום 0 (כנראה משלוח חינם/הצטרפות) - לא נוגעים
    const totalFix = total !== null && total > 0 && Math.abs((obl - total) - dlv) < 0.01 ? obl : null;
    // שלב 2: הזיכוי האוטומטי מול הזיכוי האמיתי (אחרי תיקון הסכום; syncPendingCreditRefund משתמש ב-totalAmount>0 אחרת בסכום החיובים)
    const requiredAfter = totalFix !== null ? totalFix : (total && total > 0 ? total : obl);
    const trueCredit = r2(Math.max(0, paid - requiredAfter - r2(o.other_open_refund)));
    const cur = r2(o.autoref_sum);
    const hasAuto = o.autoref != null;
    const creditFix = (hasAuto && Math.abs(cur - trueCredit) > 0.01) || (!hasAuto && trueCredit > 0.01);
    if (totalFix !== null || creditFix) {
      plan.push({ orderId: o.orderId, eventDate: o.eventDate, total, newTotal: totalFix, obl, dlv, paid, autoRefundNow: hasAuto ? cur : '', autoRefundTarget: trueCredit,
        action: !creditFix ? 'עדכון סכום בלבד' : (trueCredit === 0 ? 'מחיקה רכה של הזיכוי' : (hasAuto ? 'עדכון סכום הזיכוי' : 'יצירת זיכוי (חסר)')) });
    }
  }
  fs.mkdirSync(outDir, { recursive: true });
  const head = 'orderId,eventDate,totalNow,totalNew,obligations,delivery,paid,autoRefundNow,autoRefundTarget,action';
  const d = (x) => (x ? new Date(x).toISOString().slice(0, 10) : '');
  fs.writeFileSync(path.join(outDir, 'repair-plan-neve.csv'), '\uFEFF' + [head, ...plan.map(p => [p.orderId, d(p.eventDate), p.total ?? '', p.newTotal ?? '', p.obl, p.dlv, p.paid, p.autoRefundNow, p.autoRefundTarget, p.action].join(','))].join('\n'));
  fs.writeFileSync(path.join(outDir, 'no-delivery-charge-neve.csv'), '\uFEFF' + ['orderId,eventDate,city,direction,total,obligations,paid', ...noDelivery.map(p => [p.orderId, d(p.eventDate), p.city ?? '', p.dir ?? '', p.total ?? '', p.obl, p.paid].join(','))].join('\n'));
  const sum = (f) => plan.filter(f).reduce((s, p) => s + (Number(p.autoRefundNow || 0) - p.autoRefundTarget), 0);
  console.log(JSON.stringify({
    deliveryOrders: rows.length, planRows: plan.length,
    totalFixes: plan.filter(p => p.newTotal !== null).length,
    softDeleteRefund: plan.filter(p => p.action === 'מחיקה רכה של הזיכוי').length,
    updateRefund: plan.filter(p => p.action === 'עדכון סכום הזיכוי').length,
    createRefund: plan.filter(p => p.action.startsWith('יצירת')).length,
    amountOnlyTotal: plan.filter(p => p.action === 'עדכון סכום בלבד').length,
    excessRefundRemovedILS: r2(sum(() => true)), noDeliveryCharge: noDelivery.length
  }, null, 1));
})().catch(e => { console.error('ERR', e.message); process.exit(1); });
