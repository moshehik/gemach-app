// בדיקת קריאה בלבד (לא כותבת כלום): הזמנות משלוח ש"איבדו" את חיוב המשלוח, סכום הזמנה שמור שלא כולל משלוח, וזיכויים אוטומטיים שגויים.
// רקע וכללי הטיפול: docs/delivery-total-and-credit-fix-2026-10-12.md
//   node scripts/audit_delivery_totals_and_credits.cjs [org1|org2]     (מתוך שורש הריפו, קורא .env: PROD_DATABASE_URL / PROD_DATABASE_URL_ORG2)
// לא מדפיס כתובות חיבור. מתחבר במצב default_transaction_read_only.
const fs = require('fs');
const path = require('path');
const { Client } = require('pg');
const env = {};
for (const l of fs.readFileSync(path.join(process.cwd(), '.env'), 'utf8').split(/\r?\n/)) {
  const m = l.match(/^([A-Z_0-9]+)=(.*)$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}
const orgs = { org1: env.PROD_DATABASE_URL, org2: env.PROD_DATABASE_URL_ORG2 };
const only = process.argv[2];

const BASE = `with s as (
  select o."orderId", o."isDelivery", o."totalAmount", o."eventDate",
    coalesce((select sum(amount) from "PaymentObligation" p where p."orderId"=o."orderId" and not p."isDeleted"),0) obl,
    coalesce((select sum(amount) from "PaymentObligation" p where p."orderId"=o."orderId" and not p."isDeleted" and p.description like '%משלוח%'),0) dlv,
    coalesce((select sum(amount) from "Payment" y where y."orderId"=o."orderId" and not y."isDeleted"),0) paid,
    (select sum(amount) from "Refund" r where r."orderId"=o."orderId" and not r."isDeleted" and not r."isExecuted" and r."isAutoGenerated") autoref
  from "Order" o where coalesce(o."isDeleted",false)=false)`;

(async () => {
  for (const [org, url] of Object.entries(orgs)) {
    if (only && only !== org) continue;
    const c = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
    await c.connect();
    await c.query('SET default_transaction_read_only = on');
    console.log(`\n===== ${org} =====`);
    let r = await c.query(BASE + ` select count(*) n from s where "isDelivery"`);
    console.log('active delivery orders:', r.rows[0].n);
    r = await c.query(BASE + ` select "orderId","eventDate","totalAmount",obl,paid from s where "isDelivery" and dlv=0 order by "orderId" desc`);
    console.log('A) delivery orders with NO live delivery obligation:', r.rowCount);
    r.rows.forEach(x => console.log('  ', JSON.stringify(x)));
    r = await c.query(BASE + ` select count(*) filter (where abs(coalesce("totalAmount",0)-obl)>0.01) mism from s where "isDelivery" and dlv>0`);
    console.log('B) delivery orders whose stored totalAmount != live obligations sum:', r.rows[0].mism);
    r = await c.query(BASE + ` select "orderId",obl,paid,autoref, greatest(0, paid-obl) true_credit from s where "isDelivery" and autoref is not null and abs(autoref - greatest(0, paid-obl))>0.01 order by "orderId"`);
    console.log('C) open auto credit refunds on delivery orders whose amount != true credit (paid - obligations):', r.rowCount);
    r.rows.forEach(x => console.log('  ', JSON.stringify(x)));
    r = await c.query(`select count(*) n from "Refund" r join "Order" o on o."orderId"=r."orderId" where r."isAutoGenerated" and r."isExecuted" and not r."isDeleted" and o."isDelivery"`);
    console.log('D) EXECUTED auto refunds on delivery orders (money already paid out):', r.rows[0].n);
    await c.end();
  }
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
